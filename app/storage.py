import json
from contextlib import asynccontextmanager
from datetime import UTC, datetime
from pathlib import Path
from time import time

from app.database import connect
from app.schemas import Message, Turn
from app.services.model import Reply


class Store:
    def __init__(self, path: Path | str):
        self.path = path

    async def initialize(self):
        sqlite = isinstance(self.path, Path)
        if sqlite:
            self.path.parent.mkdir(parents=True, exist_ok=True)
        message_pk = (
            "id INTEGER PRIMARY KEY"
            if sqlite
            else "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        )
        branch_pk = (
            message_pk
            if sqlite
            else "id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY"
        )
        schema = f"""CREATE TABLE IF NOT EXISTS messages (
                    {message_pk},
                    role TEXT NOT NULL CHECK(role IN ('user', 'assistant')),
                    text TEXT NOT NULL,
                    created_at TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS sessions (
                    token_hash TEXT PRIMARY KEY,
                    expires_at DOUBLE PRECISION NOT NULL
                );
                CREATE TABLE IF NOT EXISTS branches ({branch_pk});
                CREATE TABLE IF NOT EXISTS branch_messages (
                    branch_id INTEGER NOT NULL,
                    message_id INTEGER NOT NULL,
                    PRIMARY KEY (branch_id, message_id)
                );
                CREATE TABLE IF NOT EXISTS active_branch (
                    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
                    branch_id INTEGER NOT NULL
                );
                CREATE TABLE IF NOT EXISTS message_versions (
                    message_id INTEGER PRIMARY KEY,
                    root_id INTEGER NOT NULL,
                    branch_id INTEGER NOT NULL
                );
                CREATE INDEX IF NOT EXISTS versions_by_root ON message_versions(root_id);
                CREATE TABLE IF NOT EXISTS message_feedback (
                    message_id INTEGER PRIMARY KEY,
                    rating TEXT NOT NULL CHECK (rating IN ('good', 'bad'))
                );
                CREATE TABLE IF NOT EXISTS reply_suggestions (
                    message_id INTEGER PRIMARY KEY,
                    phrases TEXT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS turn_lock (
                    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
                    request_id TEXT NOT NULL,
                    expires_at DOUBLE PRECISION NOT NULL,
                    retry_count INTEGER NOT NULL DEFAULT 0
                );
                INSERT INTO branches (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
                INSERT INTO branch_messages (branch_id, message_id)
                    SELECT 1, id FROM messages WHERE NOT EXISTS (SELECT 1 FROM active_branch) ON CONFLICT DO NOTHING;
                INSERT INTO active_branch (singleton, branch_id) VALUES (1, 1) ON CONFLICT (singleton) DO NOTHING;
        """
        async with connect(self.path) as db:
            if sqlite:
                await db.executescript(
                    "PRAGMA journal_mode = WAL; BEGIN IMMEDIATE;" + schema + "COMMIT;"
                )
            else:
                await db.execute_fetchall("SELECT pg_advisory_xact_lock(799504126)")
                for statement in schema.split(";"):
                    if statement.strip():
                        await db.execute(statement)
                await db.commit()

    async def active_branch(self) -> int:
        async with connect(self.path) as db:
            [(branch_id,)] = await db.execute_fetchall(
                "SELECT branch_id FROM active_branch"
            )
            return branch_id

    async def history(
        self, branch_id: int, *, before: int | None = None
    ) -> list[Message]:
        sql = """
            SELECT messages.id, role, text, created_at, phrases
            FROM messages JOIN branch_messages AS path ON messages.id = path.message_id
            LEFT JOIN reply_suggestions AS suggestions ON messages.id = suggestions.message_id
            WHERE path.branch_id = ?
        """
        values = (branch_id,)
        if before is not None:
            sql += " AND messages.id < ?"
            values += (before,)
        async with connect(self.path) as db:
            rows = await db.execute_fetchall(sql + " ORDER BY messages.id", values)
        return [
            Message(
                id=message_id,
                role=role,
                text=text,
                created_at=created_at,
                answer_suggestions=json.loads(phrases) if phrases else [],
            )
            for message_id, role, text, created_at, phrases in rows
        ]

    @asynccontextmanager
    async def reserve_turn(self, request_id: str):
        async with connect(self.path) as db:
            rows = await db.execute_fetchall(
                """INSERT INTO turn_lock (singleton, request_id, expires_at, retry_count)
                   VALUES (1, ?, ?, 0)
                   ON CONFLICT (singleton) DO UPDATE SET
                   request_id = excluded.request_id, expires_at = excluded.expires_at, retry_count = 0
                   WHERE turn_lock.expires_at < ? RETURNING request_id""",
                (request_id, time() + 295, time()),
            )
            await db.commit()
        try:
            yield bool(rows)
        finally:
            if rows:
                async with connect(self.path) as db:
                    await db.execute(
                        "DELETE FROM turn_lock WHERE request_id = ?", (request_id,)
                    )
                    await db.commit()

    async def set_retry_count(self, request_id: str, count: int):
        async with connect(self.path) as db:
            await db.execute(
                "UPDATE turn_lock SET retry_count = ? WHERE request_id = ?",
                (count, request_id),
            )
            await db.commit()

    async def retry_count(self, request_id: str) -> int:
        async with connect(self.path) as db:
            rows = await db.execute_fetchall(
                "SELECT retry_count FROM turn_lock WHERE request_id = ? AND expires_at > ?",
                (request_id, time()),
            )
            return rows[0][0] if rows else 0

    async def metadata(self, branch_id: int):
        async with connect(self.path) as db:
            versions = await db.execute_fetchall(
                """
                SELECT selected.message_id, variant.message_id, variant.branch_id
                FROM branch_messages AS selected
                JOIN message_versions AS original ON original.message_id = selected.message_id
                JOIN message_versions AS variant ON variant.root_id = original.root_id
                WHERE selected.branch_id = ? ORDER BY variant.message_id
            """,
                (branch_id,),
            )
            ratings = await db.execute_fetchall(
                """
                SELECT feedback.message_id, rating FROM message_feedback AS feedback
                JOIN branch_messages AS path ON path.message_id = feedback.message_id
                WHERE path.branch_id = ?
            """,
                (branch_id,),
            )
        groups = {}
        for selected_id, message_id, version_branch in versions:
            groups.setdefault(selected_id, []).append(
                {"message_id": message_id, "branch_id": version_branch}
            )
        return groups, dict(ratings)

    async def select_branch(self, branch_id: int) -> bool:
        async with connect(self.path) as db:
            cursor = await db.execute(
                "UPDATE active_branch SET branch_id = ? WHERE EXISTS (SELECT 1 FROM branches WHERE id = ?)",
                (branch_id, branch_id),
            )
            found = bool(cursor.rowcount)
            await db.commit()
            return found

    async def save_rating(self, message_id: int, rating: str | None):
        async with connect(self.path) as db:
            rows = await db.execute_fetchall(
                "SELECT id FROM messages WHERE id = ? AND role = 'assistant'",
                (message_id,),
            )
            if not rows:
                return False
            if rating is None:
                await db.execute(
                    "DELETE FROM message_feedback WHERE message_id = ?", (message_id,)
                )
            else:
                await db.execute(
                    "INSERT INTO message_feedback VALUES (?, ?) ON CONFLICT (message_id) DO UPDATE SET rating = excluded.rating",
                    (message_id, rating),
                )
            await db.commit()
            return True

    async def save_turn(
        self,
        branch_id: int,
        user_text: str,
        user_time: datetime,
        reply: Reply,
        *,
        edit_id: int | None = None,
    ) -> Turn:
        async with connect(self.path) as db:
            user = await self._insert_message(db, "user", user_text, user_time)
            assistant = await self._insert_message(
                db, "assistant", reply.text, datetime.now(UTC)
            )
            if reply.suggestions:
                await db.execute(
                    "INSERT INTO reply_suggestions VALUES (?, ?)",
                    (assistant.id, json.dumps(reply.suggestions, ensure_ascii=False)),
                )
                assistant.answer_suggestions = reply.suggestions
            if edit_id is not None:
                [(new_branch,)] = await db.execute_fetchall(
                    "INSERT INTO branches DEFAULT VALUES RETURNING id"
                )
                await db.execute(
                    "INSERT INTO branch_messages SELECT ?, message_id FROM branch_messages WHERE branch_id = ? AND message_id < ?",
                    (new_branch, branch_id, edit_id),
                )
                await db.execute(
                    "INSERT INTO message_versions VALUES (?, ?, ?) ON CONFLICT (message_id) DO NOTHING",
                    (edit_id, edit_id, branch_id),
                )
                await db.execute(
                    "INSERT INTO message_versions SELECT ?, root_id, ? FROM message_versions WHERE message_id = ?",
                    (user.id, new_branch, edit_id),
                )
                await db.execute(
                    "UPDATE active_branch SET branch_id = ?", (new_branch,)
                )
                branch_id = new_branch
            await db.executemany(
                "INSERT INTO branch_messages VALUES (?, ?)",
                ((branch_id, user.id), (branch_id, assistant.id)),
            )
            await db.commit()
        return Turn(user=user, assistant=assistant)

    @staticmethod
    async def _insert_message(db, role, text, created_at) -> Message:
        [(message_id,)] = await db.execute_fetchall(
            "INSERT INTO messages (role, text, created_at) VALUES (?, ?, ?) RETURNING id",
            (role, text, created_at.isoformat()),
        )
        return Message(id=message_id, role=role, text=text, created_at=created_at)

    async def save_session(
        self, token_hash: str, expires_at: float, previous_hash: str | None
    ):
        async with connect(self.path) as db:
            await db.execute(
                "DELETE FROM sessions WHERE expires_at <= ? OR token_hash = ?",
                (time(), previous_hash),
            )
            await db.execute(
                "INSERT INTO sessions (token_hash, expires_at) VALUES (?, ?)",
                (token_hash, expires_at),
            )
            await db.commit()

    async def has_session(self, token_hash: str) -> bool:
        async with connect(self.path) as db:
            rows = await db.execute_fetchall(
                "SELECT 1 FROM sessions WHERE token_hash = ? AND expires_at > ?",
                (token_hash, time()),
            )
        return bool(rows)

    async def delete_session(self, token_hash: str):
        async with connect(self.path) as db:
            await db.execute("DELETE FROM sessions WHERE token_hash = ?", (token_hash,))
            await db.commit()
